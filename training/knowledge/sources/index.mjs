// Joins the CSV (name, link) to the investigated catalog, verifies they agree, probes live URLs,
// and writes the citation file.
import { csvObjects, readFileSync, writeFileSync, path, HERE, fetchBuf, sleep, today, readJson, writeJson, dir, existsSync } from '../util.mjs';
import { CATALOG, ACCESSED } from './catalog.mjs';

export function loadSources() {
  const rows = csvObjects(readFileSync(path.join(HERE, 'sources', 'my_ai_training_sources.csv'), 'utf8'));
  if (rows.length !== CATALOG.length) throw new Error(`CSV has ${rows.length} rows, catalog ${CATALOG.length}`);
  return rows.map((r, i) => ({ n: i + 1, name: r.Name, url: r.Link, ...CATALOG[i] }));
}
export const byId = (id) => loadSources().find((s) => s.id === id);

const REQUIRED = ['id', 'contents', 'free', 'bulk', 'license', 'evidence', 'use', 'format', 'size', 'how', 'limits', 'quality'];
/** Catalog completeness check: every source must answer the ten investigation questions. */
export function checkCatalog(sources = loadSources()) {
  const problems = [];
  for (const s of sources) {
    for (const k of REQUIRED) if (s[k] === undefined || s[k] === '') problems.push(`${s.id}: missing ${k}`);
    if (!['train', 'eval', 'reference', 'none'].includes(s.use)) problems.push(`${s.id}: bad use ${s.use}`);
    if (!/^https?:\/\//.test(s.evidence || '')) problems.push(`${s.id}: evidence is not a URL`);
    if (/unverified/i.test(s.license) && !(s.unverified || []).length) problems.push(`${s.id}: licence marked unverified but not listed`);
    if (s.use === 'train' && /UNVERIFIED/.test(s.license) && s.nc === null) problems.push(`${s.id}: trainable with unknown licence`);
  }
  return problems;
}

/** Re-check that each CSV link still answers. Saves status per source (does not change the catalog). */
export async function probeAll({ delayMs = 300 } = {}) {
  const out = [];
  for (const s of loadSources()) {
    let status = null, err = null;
    try { await fetchBuf(s.url, { tries: 1, timeoutMs: 20000 }); status = 200; } catch (e) { status = e.status || null; err = e.message; }
    out.push({ id: s.id, url: s.url, status, error: status === 200 ? undefined : err, checked: today() });
    await sleep(delayMs);
  }
  writeJson(path.join(dir('reports'), 'source-probe.json'), out);
  return out;
}

