    '- Fonseca et al., "FSD50K: an Open Dataset of Human-Labeled Sound Events", IEEE/ACM TASLP 2022.', '- Piczak, "ESC: Dataset for Environmental Sound Classification", ACM MM 2015.',
    '- Drossos et al., "Clotho: An Audio Captioning Dataset", ICASSP 2020.', '- Livingstone & Russo, "The RAVDESS", PLoS ONE 2018.',
    '- Panayotov et al., "Librispeech: an ASR corpus based on public domain audio books", ICASSP 2015.',
    '- Wadden et al., "Fact or Fiction: Verifying Scientific Claims", EMNLP 2020 (SciFact).', '- Dasigi et al., "A Dataset of Information-Seeking Questions and Answers Anchored in Research Papers", NAACL 2021 (QASPER).',
