#!/usr/bin/env node
/**
 * Builds mobile/server/bundle/neuroclaw-server.js: the computer's own server (interface/main.ts and everything it
 * imports) as one Node-free JavaScript file for the phone apps to run, exposed as globalThis.NeuroClawServer.
 * See mobile/server/src/index.ts. Uses the shared packer (phone-bundle.mjs): the TypeScript compiler and Node
 * built-ins only; every Node module the engine imports is replaced by this project's own shim in
 * mobile/server/src/shims, so no third-party code is involved.
 *
 *   node scripts/release/build-mobile-server.mjs [--report]
 *
 * --report lists any import that still has no replacement, instead of stopping at the first.
 */
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { bundle } from './phone-bundle.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SHIMS = path.join(ROOT, 'mobile/server/src/shims');
const shim = (name) => path.join(SHIMS, `${name}.ts`);

/** Node's own module names (with and without the node: prefix) -> the phone's replacement. */
const MODULES = {
  fs: 'fs', 'fs/promises': 'fs-promises', path: 'path', os: 'os', crypto: 'crypto', url: 'url', util: 'util', vm: 'vm', http: 'http', https: 'https',
  events: 'events', zlib: 'zlib', child_process: 'child-process', net: 'net', readline: 'readline', async_hooks: 'async-hooks',
  'dns/promises': 'dns-promises', buffer: 'buffer',
};
const aliases = {};
for (const [name, file] of Object.entries(MODULES)) { aliases[name] = shim(file); aliases[`node:${name}`] = shim(file); }

export const OUT_FILE = path.join(ROOT, 'mobile/server/bundle/neuroclaw-server.js');

const result = bundle({
  root: ROOT,
  entry: path.join(ROOT, 'mobile/server/src/index.ts'),
  outFile: OUT_FILE,
  aliases,
  report: process.argv.includes('--report'),
  header: [
    '// NeuroClaw server for the phone. Generated by scripts/release/build-mobile-server.mjs',
    '// -- do not edit by hand; edit the engine or mobile/server/src/*.ts and rebuild.',
  ],
});
if (result.unresolved.size > 0) {
  for (const [spec, files] of result.unresolved) console.log(`no replacement for "${spec}" (${[...files].slice(0, 3).join(', ')})`);
  process.exit(1);
}
console.log(`Built ${path.relative(ROOT, OUT_FILE)} from ${result.modules} modules.`);
